def grid(text):
    rows = [line.strip() for line in text.strip().splitlines()]
    width = len(rows[0])
    for i, row in enumerate(rows):
        if len(row) != width:
            raise ValueError(f"row {i} is {len(row)} wide, expected {width}: {row}")
        for ch in row:
            # x and X are placeholders a recolor() fills in later.
            if ch not in ".xX" and ch not in PALETTE:
                raise ValueError(f"row {i}: unknown colour {ch!r}")
    return rows


def recolor(rows, mapping):
    return ["".join(mapping.get(ch, ch) for ch in row) for row in rows]


def flip(rows):
    return [row[::-1] for row in rows]


def vflip(rows):
    return list(reversed(rows))


def over(base, top):
    """Draw `top` over `base`; transparent pixels in `top` show `base`."""
    return ["".join(t if t != "." else b for b, t in zip(br, tr)) for br, tr in zip(base, top)]


